-- days_back must cover the deepest replay any module performs (see
-- modules.feature.backfill_days), because a write outside an existing partition
-- fails. The default leaves generous room above the configured horizon.
CREATE OR REPLACE FUNCTION alttech.ensure_all_partitions(
    days_back  INT DEFAULT 8,
    days_ahead INT DEFAULT 3)
RETURNS INTEGER
LANGUAGE plpgsql
AS $$
DECLARE
    parent  TEXT;
    created INTEGER := 0;
BEGIN
    -- Never recreate a day retention has already reclaimed: the backward window
    -- is clamped to the oldest partition that still exists (a parent with none
    -- keeps the full window). The service passes its replay horizon (13 days)
    -- for every parent, while half the parents keep 1-4 days; unclamped, each
    -- hourly advance recreated ~80 empty partitions that the next retention
    -- pass dropped again -- two AccessExclusiveLock storms an hour on the
    -- parents the feature writers hold, and the deadlocks that came with them.
    -- Same rule as alttech-schema --ensure-partitions.
    FOREACH parent IN ARRAY alttech.partitioned_parents() LOOP
        created := created + alttech.ensure_daily_partitions(
            parent::regclass,
            GREATEST(now() - make_interval(days => days_back),
                     COALESCE((SELECT min(b.lower_bound)
                               FROM alttech.partition_bounds(parent::regclass) b),
                              now() - make_interval(days => days_back))),
            now() + make_interval(days => days_ahead));
    END LOOP;
    RETURN created;
END;
$$;

-- Total on-disk bytes (heap + indexes + TOAST) of the alttech schema.
CREATE OR REPLACE FUNCTION alttech.schema_bytes()
RETURNS BIGINT
LANGUAGE sql
STABLE
AS $$
    SELECT COALESCE(SUM(pg_total_relation_size(c.oid)), 0)::bigint
    FROM pg_class c
    JOIN pg_namespace n ON n.oid = c.relnamespace
    WHERE n.nspname = 'alttech' AND c.relkind IN ('r','p','m','t');
$$;

-- Read-only measurement of the AltSpotter schema, for the shared database
-- budget view. AltTech never writes or drops anything in public.
CREATE OR REPLACE FUNCTION alttech.public_schema_bytes()
RETURNS BIGINT
LANGUAGE sql
STABLE
AS $$
    SELECT COALESCE(SUM(pg_total_relation_size(c.oid)), 0)::bigint
    FROM pg_class c
    JOIN pg_namespace n ON n.oid = c.relnamespace
    WHERE n.nspname = 'public' AND c.relkind IN ('r','p','m','t');
$$;

