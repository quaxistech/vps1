-- AltTech analytics schema.
--
-- AltTech owns the `alttech` schema and nothing else. AltSpotter owns the
-- market-data tables in `public`; AltTech reads them strictly read-only and
-- never creates, alters or drops anything there.
--
-- Conventions
--   * every timestamp is TIMESTAMPTZ in UTC;
--   * analytics values are stored compactly as REAL[] with a validity bitmap,
--     the value order being defined by (feature_set_version_id, position);
--   * money read from AltSpotter stays NUMERIC on the read side and is never
--     round-tripped through binary floating point;
--   * every time series is RANGE-partitioned by day so retention and the
--     storage budget are enforced by whole-partition DROP.
--
-- The file is idempotent (CREATE ... IF NOT EXISTS) and applied by
-- `alttech-schema`, which records its SHA-256 in alttech.schema_version.

CREATE SCHEMA IF NOT EXISTS alttech;

CREATE TABLE IF NOT EXISTS alttech.schema_version (
    singleton  BOOLEAN PRIMARY KEY DEFAULT true CHECK (singleton),
    checksum   TEXT NOT NULL,
    applied_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------------------
-- Partition helpers. Namespaced to `alttech` so AltTech partition maintenance
-- can never touch a public (AltSpotter) table.
-- ---------------------------------------------------------------------------

-- Idempotently create daily range partitions of `parent` covering
-- [from_ts, to_ts]. Partition names are <parent>_YYYYMMDD.
CREATE OR REPLACE FUNCTION alttech.ensure_daily_partitions(
    parent  regclass,
    from_ts TIMESTAMPTZ,
    to_ts   TIMESTAMPTZ)
RETURNS INTEGER
LANGUAGE plpgsql
AS $$
DECLARE
    lo      TIMESTAMPTZ;
    hi      TIMESTAMPTZ;
    pname   TEXT;
    created INTEGER := 0;
BEGIN
    lo := date_trunc('day', from_ts AT TIME ZONE 'UTC') AT TIME ZONE 'UTC';
    WHILE lo <= to_ts LOOP
        hi := lo + interval '1 day';
        -- parent::text is schema-qualified (alttech.foo); to_regclass resolves it.
        pname := parent::text || '_' || to_char(lo AT TIME ZONE 'UTC', 'YYYYMMDD');
        IF to_regclass(pname) IS NULL THEN
            EXECUTE format('CREATE TABLE %s PARTITION OF %s FOR VALUES FROM (%L) TO (%L)',
                           pname, parent::text, lo, hi);
            created := created + 1;
        END IF;
        lo := hi;
    END LOOP;
    RETURN created;
END;
$$;

-- List the range partitions of `parent` with their bounds (retention drops).
CREATE OR REPLACE FUNCTION alttech.partition_bounds(parent regclass)
RETURNS TABLE (partition_name TEXT, lower_bound TIMESTAMPTZ, upper_bound TIMESTAMPTZ)
LANGUAGE plpgsql
AS $$
DECLARE
    r    RECORD;
    expr TEXT;
    lo   TEXT;
    hi   TEXT;
BEGIN
    FOR r IN
        SELECT c.oid, n.nspname, c.relname
        FROM pg_inherits i
        JOIN pg_class c ON c.oid = i.inhrelid
        JOIN pg_namespace n ON n.oid = c.relnamespace
        WHERE i.inhparent = parent
    LOOP
        expr := pg_get_expr((SELECT relpartbound FROM pg_class WHERE oid = r.oid), r.oid);
        lo := substring(expr FROM 'FROM \(''([^'']+)''\)');
        hi := substring(expr FROM 'TO \(''([^'']+)''\)');
        IF lo IS NOT NULL AND hi IS NOT NULL THEN
            partition_name := r.nspname || '.' || r.relname;
            lower_bound := lo::timestamptz;
            upper_bound := hi::timestamptz;
            RETURN NEXT;
        END IF;
    END LOOP;
END;
$$;

