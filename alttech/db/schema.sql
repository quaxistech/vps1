-- ---------------------------------------------------------------------------
-- Retention and storage budget.
--
-- `target_keep` is derived from the trading horizon: orders live at most 48 h,
-- so every input a decision can be attributed to must stay queryable for the
-- full order lifetime plus a review margin. Sub-minute microstructure is an
-- execution-timing signal and is kept only intraday; bar-level analytics are
-- kept for several days; regimes and structure, which are cheap and used for
-- longer-horizon context, are kept longest.
--
-- `cleanup_priority` ascending = dropped first when the schema approaches its
-- budget. `minimum_keep` is the floor budget pressure may never cut below;
-- `protected` families are dropped only after every unprotected one.
-- ---------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS alttech.retention_policies (
    table_name       TEXT PRIMARY KEY,
    target_keep      INTERVAL NOT NULL,
    minimum_keep     INTERVAL NOT NULL,
    cleanup_priority INTEGER NOT NULL,
    protected        BOOLEAN NOT NULL DEFAULT false,
    rationale        TEXT NOT NULL DEFAULT '',
    updated_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT chk_target_ge_min CHECK (target_keep >= minimum_keep)
);

