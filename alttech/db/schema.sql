    status                 TEXT        NOT NULL DEFAULT 'VALID'
        CHECK (status IN ('NOT_READY','WARMING','VALID','INCOMPLETE_INPUT','REVISED','INVALID')),
    valid_count            INTEGER     NOT NULL DEFAULT 0,
    computed_at            TIMESTAMPTZ NOT NULL DEFAULT now(),
