-- altmacro — external market and macro reference data for VPS1.
--
-- This service delivers RAW -> NORMALIZED -> VALID HISTORICAL SERIES ->
-- TIMESTAMPED/AVAILABILITY-MARKED -> PUBLISHED. It states what a number is,
-- where it came from and when it became knowable. It does not state what a
-- number means for trading: no correlation, no beta, no lead-lag, no z-score,
-- no regime. Those are AltTech's and AltML's to discover.
--
-- AltSpotter remains authoritative for crypto. Nothing here duplicates it.

BEGIN;

-- ---------------------------------------------------------------------------
-- Providers
-- ---------------------------------------------------------------------------

-- One row per external data source. `access` records how the source is
-- reached so that an operator can tell at a glance which series would stop if
-- a credential were withdrawn; secrets themselves live only in the runtime
-- environment and are never stored here.
CREATE TABLE macro_providers (
    id                  SMALLINT PRIMARY KEY,
    code                TEXT NOT NULL UNIQUE,
    display_name        TEXT NOT NULL,
    access              TEXT NOT NULL
                        CHECK (access IN ('keyless', 'api_key_required')),
    base_url            TEXT NOT NULL,
    terms_url           TEXT,
    -- Politeness budget the bootstrap and poller must respect.
    rate_limit_per_min  INTEGER NOT NULL DEFAULT 30 CHECK (rate_limit_per_min > 0),
    -- Where that number comes from. A published limit can be relied on; a
    -- measured one is a guess with evidence behind it and must be treated more
    -- cautiously, because the server is free to change it without telling us.
    rate_limit_source   TEXT NOT NULL DEFAULT 'observed'
                        CHECK (rate_limit_source IN ('documented', 'observed')),
    -- URL of the document the limit was read from, when it was documented.
    rate_limit_ref      TEXT,
    -- Attribution the source requires of anything built on it.
    attribution_notice  TEXT,
    CONSTRAINT chk_documented_limit_has_reference CHECK (
        rate_limit_source <> 'documented' OR rate_limit_ref IS NOT NULL),
    enabled             BOOLEAN NOT NULL DEFAULT true,
    notes               TEXT,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Rolling health of each provider, updated by the poller. Kept separate from
-- the registry so that configuration and observed state never overwrite one
-- another.
CREATE TABLE macro_provider_metadata (
    provider_id             SMALLINT PRIMARY KEY REFERENCES macro_providers(id),
    last_attempt_at         TIMESTAMPTZ,
    last_success_at         TIMESTAMPTZ,
    last_failure_at         TIMESTAMPTZ,
    last_failure_reason     TEXT,
    consecutive_failures    INTEGER NOT NULL DEFAULT 0 CHECK (consecutive_failures >= 0),
    requests_today          INTEGER NOT NULL DEFAULT 0 CHECK (requests_today >= 0),
    requests_today_date     DATE,
    updated_at              TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------------------
-- Instruments
-- ---------------------------------------------------------------------------

-- The canonical catalogue. `series_class` is the single most important field
-- in this schema: it prevents an offshore market quote, an official reference
-- rate and a central-bank fixing from ever being read as the same thing.
--
--   MARKET             a tradable price formed by a market (USDCNH, XAUUSD)
--   OFFICIAL_REFERENCE a rate published by an authority as a reference, not a
--                      tradable quote (Fed H.10 USD/CNY, ECB EUR reference,
--                      PBOC central parity, LBMA fixing)
--   ECONOMIC_RELEASE   a statistic published on a schedule, revisable
--   DERIVED            computed here from other series; the derivation is
--                      recorded and is arithmetic only (e.g. a currency cross),
--                      never an interpretation
CREATE TABLE macro_instruments (
    id                          BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    code                        TEXT NOT NULL UNIQUE,
    display_name                TEXT NOT NULL,
    series_class                TEXT NOT NULL
                                CHECK (series_class IN ('MARKET', 'OFFICIAL_REFERENCE',
                                                        'ECONOMIC_RELEASE', 'DERIVED')),
    -- What the number counts. Stored in the source's own denomination:
    -- changing it here would silently rewrite economic meaning.
    unit                        TEXT NOT NULL
                                CHECK (unit IN ('price_ratio', 'percent_per_annum',
                                                'index_points', 'currency_amount', 'count')),
    base_asset                  TEXT,
    quote_asset                 TEXT,
    -- Free text stating the denomination exactly as the source publishes it,
    -- e.g. 'CNY per EUR', 'JPY per USD', 'USD per troy ounce'.
    denomination                TEXT NOT NULL,
    -- Native sampling of the series as published.
    native_frequency            TEXT NOT NULL
                                CHECK (native_frequency IN ('tick', 'minute', 'hourly',
                                                            'daily', 'weekly', 'monthly',
                                                            'quarterly', 'irregular')),
    -- Calendar that decides whether an absent observation is a gap or a
    -- legitimate closure.
    session_calendar            TEXT NOT NULL DEFAULT 'none'
                                CHECK (session_calendar IN ('none', 'fx_24x5', 'us_business',
                                                            'uk_business', 'cn_business',
                                                            'target2', 'us_equity')),
    -- Actual first observation this service has been able to obtain. Written
    -- from what was really fetched. History is never synthesised to fill a
    -- range, so a consumer can always tell where evidence begins.
    earliest_available_timestamp TIMESTAMPTZ,
    latest_observed_timestamp    TIMESTAMPTZ,
    -- Set only for DERIVED rows: the arithmetic, in words, and its inputs.
    derivation                  TEXT,
    enabled                     BOOLEAN NOT NULL DEFAULT true,
    created_at                  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at                  TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT chk_derivation_only_for_derived CHECK (
        (series_class = 'DERIVED') = (derivation IS NOT NULL))
);

-- How a given instrument is obtained from a given provider. A provider switch
-- must never silently change what the number is, so every semantic that could
-- differ between providers is pinned here and compared on switch.
CREATE TABLE macro_instrument_sources (
    id                      BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    instrument_id           BIGINT NOT NULL REFERENCES macro_instruments(id) ON DELETE CASCADE,
    provider_id             SMALLINT NOT NULL REFERENCES macro_providers(id),
    -- The symbol/series id in the provider's own namespace, verified against
    -- the provider's catalogue — never guessed.
    native_symbol           TEXT NOT NULL,
    -- Which side of the market the stored price is. A provider that returns
    -- mid where another returned bid is a different series, not a fallback.
    price_basis             TEXT NOT NULL
                            CHECK (price_basis IN ('bid', 'ask', 'mid', 'last',
                                                   'fixing', 'close', 'not_applicable')),
    -- What the row's timestamp refers to.
    timestamp_semantics     TEXT NOT NULL
                            CHECK (timestamp_semantics IN ('bar_open', 'bar_close',
                                                           'point_in_time', 'observation_date')),
    source_timezone         TEXT NOT NULL DEFAULT 'UTC',
    -- 1 = primary, higher = fallback, tried in ascending order.
    priority                SMALLINT NOT NULL DEFAULT 1 CHECK (priority >= 1),
    -- Providers that ship prices as scaled integers (Dukascopy) need the
    -- instrument's scale to decode them. The value is NOT guessed from the
    -- quote currency: it is established once against the instrument's official
    -- daily reference for the same date and then pinned here, and the loader
    -- refuses a decode that lands outside `sanity_min`..`sanity_max`. A wrong
    -- scale is silent — it yields a well-formed series off by a factor of ten.
    decode_scale            NUMERIC CHECK (decode_scale IS NULL OR decode_scale > 0),
    sanity_min              NUMERIC,
    sanity_max              NUMERIC,
    CONSTRAINT chk_sanity_band CHECK (
        sanity_min IS NULL OR sanity_max IS NULL OR sanity_max > sanity_min),
    CONSTRAINT chk_scale_has_sanity_band CHECK (
        decode_scale IS NULL OR (sanity_min IS NOT NULL AND sanity_max IS NOT NULL)),
    enabled                 BOOLEAN NOT NULL DEFAULT true,
    created_at              TIMESTAMPTZ NOT NULL DEFAULT now(),
    -- A provider that publishes both sides of the market (Dukascopy ships bid
    -- and ask as separate files) is two sources, not one: bid and ask are
    -- different series and are stored as such.
    UNIQUE (instrument_id, provider_id, native_symbol, price_basis),
    -- Fallback order is resolved within one basis, so switching provider can
    -- never silently move a series from bid to mid.
    UNIQUE (instrument_id, price_basis, priority)
);

COMMIT;

BEGIN;

-- ---------------------------------------------------------------------------
-- Quality vocabulary
-- ---------------------------------------------------------------------------
--
-- Every stored observation carries one of these. The rule the whole service is
-- built around: an absent number is never written as zero, and a market that
-- is legitimately shut is never written as an error.
--
--   VALID           the source published a number and it passed validation
--   STALE           carried forward: the source has not updated within the
--                   series' expected cadence; value is the last known one and
--                   `value_as_of` says how old it is
--   MISSING         an observation was expected and did not arrive
--   PROVIDER_ERROR  the provider failed or returned something unusable
--   MARKET_CLOSED   no observation was expected: weekend, holiday, out of session
--   PARTIAL         the bar or period is incomplete (still forming, or the
--                   source returned a truncated range)
--
-- Only VALID and STALE rows carry a value. MISSING, PROVIDER_ERROR,
-- MARKET_CLOSED and PARTIAL rows exist to record the absence explicitly, which
-- is information a consumer needs and cannot reconstruct from a hole.

-- ---------------------------------------------------------------------------
-- Market bars (intraday and daily OHLC from MARKET-class sources)
-- ---------------------------------------------------------------------------

CREATE TABLE macro_price_bars (
    instrument_id       BIGINT      NOT NULL REFERENCES macro_instruments(id),
    provider_id         SMALLINT    NOT NULL REFERENCES macro_providers(id),
    timeframe           TEXT        NOT NULL
                        CHECK (timeframe IN ('1m', '5m', '15m', '1h', '1d')),
    -- When the bar happened in the market. Always UTC, always bar OPEN.
    event_time          TIMESTAMPTZ NOT NULL,
    -- When this service learned of it. The pair (event_time, ingest_time) is
    -- what lets a consumer avoid look-ahead: never select on event_time alone.
    ingest_time         TIMESTAMPTZ NOT NULL DEFAULT now(),
    open                NUMERIC,
    high                NUMERIC,
    low                 NUMERIC,
    close               NUMERIC,
    -- Provider-reported activity in the provider's own unit. Not normalised
    -- across providers, because volume is not comparable across them.
    volume              NUMERIC,
    price_basis         TEXT        NOT NULL
                        CHECK (price_basis IN ('bid', 'ask', 'mid', 'last', 'close')),
    quality_status      TEXT        NOT NULL
                        CHECK (quality_status IN ('VALID', 'STALE', 'MISSING',
                                                  'PROVIDER_ERROR', 'MARKET_CLOSED', 'PARTIAL')),
    quality_reason      TEXT,
    revision            BIGINT      NOT NULL DEFAULT 0,
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (instrument_id, provider_id, timeframe, price_basis, event_time),
    -- OHLC coherence, enforced only where a value actually exists.
    CONSTRAINT chk_bar_ohlc CHECK (
        open IS NULL OR high IS NULL OR low IS NULL OR close IS NULL OR
        (high >= open AND high >= close AND high >= low AND
         low  <= open AND low  <= close)),
    CONSTRAINT chk_bar_prices CHECK (
        (open IS NULL OR open > 0) AND (high IS NULL OR high > 0) AND
        (low  IS NULL OR low  > 0) AND (close IS NULL OR close > 0)),
    CONSTRAINT chk_bar_volume CHECK (volume IS NULL OR volume >= 0),
    -- The core anti-zero rule: a non-VALID/STALE row must not carry a price.
    CONSTRAINT chk_bar_absence_is_explicit CHECK (
        quality_status IN ('VALID', 'STALE', 'PARTIAL')
        OR (open IS NULL AND high IS NULL AND low IS NULL AND close IS NULL)),
    CONSTRAINT chk_bar_valid_has_value CHECK (
        quality_status <> 'VALID'
        OR (open IS NOT NULL AND high IS NOT NULL AND low IS NOT NULL AND close IS NOT NULL))
) PARTITION BY RANGE (event_time);

CREATE INDEX idx_bars_ingest ON macro_price_bars (instrument_id, ingest_time);
CREATE INDEX idx_bars_quality ON macro_price_bars (quality_status, event_time)
    WHERE quality_status <> 'VALID';

-- ---------------------------------------------------------------------------
-- Reference values (single-number series: fixings, official rates, indices)
-- ---------------------------------------------------------------------------

CREATE TABLE macro_reference_values (
    instrument_id       BIGINT      NOT NULL REFERENCES macro_instruments(id),
    provider_id         SMALLINT    NOT NULL REFERENCES macro_providers(id),
    -- The date or instant the number refers to, in the source's own terms.
    event_time          TIMESTAMPTZ NOT NULL,
    ingest_time         TIMESTAMPTZ NOT NULL DEFAULT now(),
    -- When the value became publicly knowable, when the source states it.
    -- NULL means the source does not publish a release time; a consumer must
    -- then fall back to ingest_time, which is a bound, not the truth.
    publication_time    TIMESTAMPTZ,
    value               NUMERIC,
    -- For a STALE row: the event_time of the value being carried forward.
    value_as_of         TIMESTAMPTZ,
    quality_status      TEXT        NOT NULL
                        CHECK (quality_status IN ('VALID', 'STALE', 'MISSING',
                                                  'PROVIDER_ERROR', 'MARKET_CLOSED', 'PARTIAL')),
    quality_reason      TEXT,
    revision            BIGINT      NOT NULL DEFAULT 0,
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (instrument_id, provider_id, event_time),
    CONSTRAINT chk_ref_absence_is_explicit CHECK (
        quality_status IN ('VALID', 'STALE') OR value IS NULL),
    CONSTRAINT chk_ref_valid_has_value CHECK (
        quality_status <> 'VALID' OR value IS NOT NULL),
    CONSTRAINT chk_ref_stale_is_dated CHECK (
        quality_status <> 'STALE' OR (value IS NOT NULL AND value_as_of IS NOT NULL))
);

CREATE INDEX idx_ref_publication ON macro_reference_values (instrument_id, publication_time);
CREATE INDEX idx_ref_ingest ON macro_reference_values (instrument_id, ingest_time);

COMMIT;

BEGIN;

-- ---------------------------------------------------------------------------
-- Economic releases (revisable statistics)
-- ---------------------------------------------------------------------------
--
-- A release has two clocks and they must never be conflated:
--   observation_time  the period the statistic describes (e.g. "August 2026")
--   publication_time  when it was first made public
-- and it may be revised, so the same observation_time can hold several
-- vintages. Training on the number a model could not yet have seen is the
-- single easiest way to manufacture a look-ahead edge, so availability is
-- always by publication, never by observation.
CREATE TABLE macro_events (
    id                  BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    instrument_id       BIGINT      NOT NULL REFERENCES macro_instruments(id),
    provider_id         SMALLINT    NOT NULL REFERENCES macro_providers(id),
    observation_time    TIMESTAMPTZ NOT NULL,
    publication_time    TIMESTAMPTZ,
    ingest_time         TIMESTAMPTZ NOT NULL DEFAULT now(),
    -- The date of the source's own snapshot of its database. For ALFRED this
    -- is the vintage date; a value read as-of this date is what a model could
    -- have seen on that date.
    vintage_date        DATE,
    -- 0 = first publication, increments with each revision seen.
    revision            INTEGER     NOT NULL DEFAULT 0 CHECK (revision >= 0),
    value               NUMERIC,
    quality_status      TEXT        NOT NULL
                        CHECK (quality_status IN ('VALID', 'STALE', 'MISSING',
                                                  'PROVIDER_ERROR', 'MARKET_CLOSED', 'PARTIAL')),
    quality_reason      TEXT,
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    -- One row per (series, period, vintage): revisions coexist, they do not
    -- overwrite. Without this, history silently rewrites itself.
    UNIQUE (instrument_id, provider_id, observation_time, vintage_date),
    CONSTRAINT chk_event_absence_is_explicit CHECK (
        quality_status IN ('VALID', 'STALE') OR value IS NULL),
    CONSTRAINT chk_event_valid_has_value CHECK (
        quality_status <> 'VALID' OR value IS NOT NULL)
);

CREATE INDEX idx_events_availability ON macro_events (instrument_id, publication_time);
CREATE INDEX idx_events_observation ON macro_events (instrument_id, observation_time);

-- ---------------------------------------------------------------------------
-- Ingestion bookkeeping
-- ---------------------------------------------------------------------------

-- Resumable cursor per (instrument, provider, timeframe). A bootstrap that is
-- killed halfway must restart from here, not from the beginning, and must not
-- re-request what it already stored.
CREATE TABLE macro_ingest_cursors (
    instrument_id       BIGINT      NOT NULL REFERENCES macro_instruments(id) ON DELETE CASCADE,
    provider_id         SMALLINT    NOT NULL REFERENCES macro_providers(id),
    timeframe           TEXT        NOT NULL,
    -- The side of the book is part of the cursor's identity, because bid and
    -- ask are fetched as separate series from separate files. Leaving it out
    -- makes the two share one watermark: the first side to finish marks the
    -- window complete and the second is skipped in silence, which is precisely
    -- the kind of invisible half-loss this service exists to prevent.
    price_basis         TEXT        NOT NULL DEFAULT 'not_applicable',
    -- Everything strictly before this instant has been fetched and stored,
    -- including the explicit MARKET_CLOSED and MISSING markers.
    watermark           TIMESTAMPTZ NOT NULL,
    -- The oldest instant this cursor has walked back to, for backfill.
    backfilled_from     TIMESTAMPTZ,
    last_run_at         TIMESTAMPTZ,
    last_error          TEXT,
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (instrument_id, provider_id, timeframe, price_basis)
);

-- Every fetch attempt, so that a provider's behaviour over time is evidence
-- rather than recollection.
CREATE TABLE macro_ingest_runs (
    id                  BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    provider_id         SMALLINT    NOT NULL REFERENCES macro_providers(id),
    instrument_id       BIGINT      REFERENCES macro_instruments(id) ON DELETE SET NULL,
    kind                TEXT        NOT NULL CHECK (kind IN ('bootstrap', 'poll', 'backfill', 'repair')),
    range_start         TIMESTAMPTZ,
    range_end           TIMESTAMPTZ,
    started_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    finished_at         TIMESTAMPTZ,
    http_status         INTEGER,
    rows_written        INTEGER NOT NULL DEFAULT 0,
    outcome             TEXT        NOT NULL DEFAULT 'running'
                        CHECK (outcome IN ('running', 'ok', 'empty', 'rate_limited',
                                           'provider_error', 'parse_error', 'aborted')),
    detail              TEXT
);

CREATE INDEX idx_runs_recent ON macro_ingest_runs (provider_id, started_at DESC);

-- Gaps found by the detector: a stretch where observations were expected by
-- the series' own calendar and did not arrive. Recording them makes coverage a
-- queryable fact instead of an assumption.
CREATE TABLE macro_series_gaps (
    id                  BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    instrument_id       BIGINT      NOT NULL REFERENCES macro_instruments(id) ON DELETE CASCADE,
    provider_id         SMALLINT    NOT NULL REFERENCES macro_providers(id),
    timeframe           TEXT        NOT NULL,
    gap_start           TIMESTAMPTZ NOT NULL,
    gap_end             TIMESTAMPTZ NOT NULL,
    expected_points     INTEGER,
    detected_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    resolved_at         TIMESTAMPTZ,
    resolution          TEXT CHECK (resolution IN ('backfilled', 'confirmed_absent_at_source',
                                                   'market_closed', 'unresolved')),
    UNIQUE (instrument_id, provider_id, timeframe, gap_start),
    CONSTRAINT chk_gap_order CHECK (gap_end > gap_start)
);

COMMIT;
