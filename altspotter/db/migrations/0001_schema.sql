CREATE TABLE market_candles_1m (
    exchange_id             SMALLINT    NOT NULL,
    instrument_id           BIGINT      NOT NULL,
    open_time               TIMESTAMPTZ NOT NULL,
    close_time              TIMESTAMPTZ NOT NULL,
    open                    NUMERIC     NOT NULL,
    high                    NUMERIC     NOT NULL,
    low                     NUMERIC     NOT NULL,
    close                   NUMERIC     NOT NULL,
    base_volume             NUMERIC     NOT NULL DEFAULT 0,
    quote_volume            NUMERIC     NOT NULL DEFAULT 0,
    trade_count             BIGINT,
    taker_buy_base_volume   NUMERIC,
    taker_sell_base_volume  NUMERIC,
    is_closed               BOOLEAN     NOT NULL DEFAULT true,
    source                  TEXT        NOT NULL
        CHECK (source IN ('ws', 'rest_bootstrap', 'rest_reconcile', 'rest_repair', 'aggregation')),
    quality_status          TEXT        NOT NULL DEFAULT 'ok'
        CHECK (quality_status IN ('ok', 'incomplete', 'suspect')),
    revision                BIGINT      NOT NULL DEFAULT 0,
    exchange_received_at    TIMESTAMPTZ,
    stored_at               TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at              TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (exchange_id, instrument_id, open_time),
    CONSTRAINT chk_1m_ohlc CHECK (
        high >= open AND high >= close AND high >= low AND low <= open AND low <= close),
    CONSTRAINT chk_1m_volumes CHECK (base_volume >= 0 AND quote_volume >= 0),
    CONSTRAINT chk_1m_prices CHECK (open >= 0 AND high >= 0 AND low >= 0 AND close >= 0),
    CONSTRAINT chk_1m_times CHECK (close_time = open_time + interval '1 minute')
) PARTITION BY RANGE (open_time);

