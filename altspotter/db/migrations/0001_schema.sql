-- Declarative targets/minimums per (logical table, retention class). Class:
-- 'core', 'other' or 'all' when the table has no class dimension. Under
-- storage pressure the retention_manager walks policies by cleanup_priority
-- (lower first) and may shrink from target_keep down to minimum_keep; it
-- never drops below minimum_keep.
CREATE TABLE retention_policies (
    table_name        TEXT NOT NULL,
    retention_class   TEXT NOT NULL CHECK (retention_class IN ('core', 'other', 'all')),
    target_keep       INTERVAL NOT NULL,
    minimum_keep      INTERVAL NOT NULL,
    granularity       TEXT NOT NULL CHECK (granularity IN ('hour', 'day', 'month')),
    cleanup_priority  INTEGER NOT NULL,  -- lower = dropped earlier under pressure
    updated_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (table_name, retention_class),
    CONSTRAINT chk_target_ge_min CHECK (target_keep >= minimum_keep)
);

