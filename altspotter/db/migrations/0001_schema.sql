-- altspotter PostgreSQL schema (baseline).
--
-- Conventions:
--   * every timestamp is TIMESTAMPTZ in UTC;
--   * prices/sizes/volumes are NUMERIC (exact decimal, never binary float);
--   * every market row is keyed by (exchange_id, instrument_id, time);
--   * high-volume tables are partitioned so retention works by dropping whole
--     partitions, never by row-level DELETEs:
--       - candles / 1m context / 1m aggregates: monthly RANGE partitions;
--       - raw trades / book snapshots: LIST by retention_class (1 = core,
--         0 = other), each RANGE-subpartitioned by HOUR (they grow fastest and
--         are kept for hours, so retention needs hour-level granularity);
--       - 1s aggregates: LIST by retention_class, RANGE-subpartitioned by hour
--         (same reason: their horizon is measured in hours to days).

