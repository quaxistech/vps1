CREATE TABLE market_trades_raw (
    exchange_id     SMALLINT    NOT NULL,
    instrument_id   BIGINT      NOT NULL,
    trade_time      TIMESTAMPTZ NOT NULL,          -- exchange event time
    trade_id        TEXT        NOT NULL,          -- exchange trade id (dedupe)
    price           NUMERIC     NOT NULL CHECK (price >= 0),
    size            NUMERIC     NOT NULL CHECK (size >= 0),
    side            TEXT        NOT NULL CHECK (side IN ('buy', 'sell')),  -- aggressor side
    retention_class SMALLINT    NOT NULL DEFAULT 0,  -- 1 = core, 0 = other
    received_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (retention_class, exchange_id, instrument_id, trade_time, trade_id)
) PARTITION BY LIST (retention_class);

