-- Idempotently create monthly partitions for both candle tables in [from_ts, to_ts].
CREATE OR REPLACE FUNCTION altspotter_ensure_candle_partitions(from_ts TIMESTAMPTZ, to_ts TIMESTAMPTZ)
RETURNS INTEGER
LANGUAGE plpgsql
AS $$
DECLARE
    month_start DATE := date_trunc('month', from_ts AT TIME ZONE 'UTC')::date;
    month_last  DATE := date_trunc('month', to_ts AT TIME ZONE 'UTC')::date;
    month_next  DATE;
    tbl         TEXT;
    part        TEXT;
    created     INTEGER := 0;
BEGIN
    IF month_start > month_last THEN
        RAISE EXCEPTION 'invalid partition range: % > %', from_ts, to_ts;
    END IF;
    WHILE month_start <= month_last LOOP
        month_next := (month_start + INTERVAL '1 month')::date;
        FOREACH tbl IN ARRAY ARRAY['market_candles_1m', 'market_candles_agg'] LOOP
            part := tbl || '_' || to_char(month_start, 'YYYYMM');
            IF NOT EXISTS (
                SELECT 1 FROM pg_class c
                JOIN pg_namespace n ON n.oid = c.relnamespace
                WHERE c.relname = part AND n.nspname = current_schema()
            ) THEN
                EXECUTE format(
                    'CREATE TABLE %I PARTITION OF %I FOR VALUES FROM (%L) TO (%L)',
                    part, tbl,
                    month_start::timestamptz, month_next::timestamptz);
                created := created + 1;
            END IF;
        END LOOP;
        month_start := month_next;
    END LOOP;
    RETURN created;
END;
$$;

-- Idempotently create range partitions of `parent` covering [from_ts, to_ts].
-- granularity: 'hour' | 'day' | 'month'.
-- Partition names: <parent>_YYYYMMDDHH24 / _YYYYMMDD / _YYYYMM.
CREATE OR REPLACE FUNCTION altspotter_ensure_time_partitions(
    parent      regclass,
    granularity TEXT,
    from_ts     TIMESTAMPTZ,
    to_ts       TIMESTAMPTZ)
RETURNS INTEGER
LANGUAGE plpgsql
AS $$
DECLARE
    step     INTERVAL;
    fmt      TEXT;
    lo       TIMESTAMPTZ;
    hi       TIMESTAMPTZ;
    pname    TEXT;
    created  INTEGER := 0;
BEGIN
    IF granularity = 'hour' THEN
        step := interval '1 hour'; fmt := 'YYYYMMDDHH24';
        lo := date_trunc('hour', from_ts AT TIME ZONE 'UTC') AT TIME ZONE 'UTC';
    ELSIF granularity = 'day' THEN
        step := interval '1 day'; fmt := 'YYYYMMDD';
        lo := date_trunc('day', from_ts AT TIME ZONE 'UTC') AT TIME ZONE 'UTC';
    ELSIF granularity = 'month' THEN
        step := interval '1 month'; fmt := 'YYYYMM';
        lo := date_trunc('month', from_ts AT TIME ZONE 'UTC') AT TIME ZONE 'UTC';
    ELSE
        RAISE EXCEPTION 'unsupported granularity: %', granularity;
    END IF;
    WHILE lo <= to_ts LOOP
        hi := lo + step;
        pname := parent::text || '_' || to_char(lo AT TIME ZONE 'UTC', fmt);
        IF to_regclass(pname) IS NULL THEN
            EXECUTE format('CREATE TABLE %I PARTITION OF %s FOR VALUES FROM (%L) TO (%L)',
                           pname, parent::text, lo, hi);
            created := created + 1;
        END IF;
        lo := hi;
    END LOOP;
    RETURN created;
END;
$$;

-- List range partitions of `parent` with their time bounds (for retention drops).
CREATE OR REPLACE FUNCTION altspotter_partition_bounds(parent regclass)
RETURNS TABLE (partition_name TEXT, lower_bound TIMESTAMPTZ, upper_bound TIMESTAMPTZ)
LANGUAGE plpgsql
AS $$
DECLARE
    r RECORD;
    expr TEXT;
    lo TEXT;
    hi TEXT;
BEGIN
    FOR r IN
        SELECT c.oid, c.relname
        FROM pg_inherits i JOIN pg_class c ON c.oid = i.inhrelid
        WHERE i.inhparent = parent
    LOOP
        expr := pg_get_expr((SELECT relpartbound FROM pg_class WHERE oid = r.oid), r.oid);
        lo := substring(expr FROM 'FROM \(''([^'']+)''\)');
        hi := substring(expr FROM 'TO \(''([^'']+)''\)');
        IF lo IS NOT NULL AND hi IS NOT NULL THEN
            partition_name := r.relname;
            lower_bound := lo::timestamptz;
            upper_bound := hi::timestamptz;
            RETURN NEXT;
        END IF;
    END LOOP;
END;
$$;

-- Hourly partition maintenance for the raw microstructure tables.
--
-- These are HOURLY, not daily, on purpose. Raw books and trades are the fastest
-- growing tables and are kept for hours, not days. With daily partitions the
-- whole day's data sits in one partition whose upper bound is in the future, so
-- retention (which only drops whole partitions) cannot reclaim a single byte
-- until midnight — a database that fills up mid-day would stay degraded until
-- the next day. Hourly partitions give retention a granularity it can actually
-- act on.
CREATE OR REPLACE FUNCTION altspotter_ensure_microstructure_partitions(
    hours_back INT DEFAULT 6, hours_ahead INT DEFAULT 12)
RETURNS void LANGUAGE plpgsql AS $$
BEGIN
    PERFORM altspotter_ensure_time_partitions(t, 'hour',
                                       now() - make_interval(hours => hours_back),
                                       now() + make_interval(hours => hours_ahead))
    FROM unnest(ARRAY['market_trades_raw_core', 'market_trades_raw_other',
                      'market_orderbook_snapshots_core',
                      'market_orderbook_snapshots_other',
                      'market_trade_aggregates_1s_core',
                      'market_trade_aggregates_1s_other',
                      'market_book_aggregates_1s_core',
                      'market_book_aggregates_1s_other']::regclass[]) AS t;
END;
$$;

