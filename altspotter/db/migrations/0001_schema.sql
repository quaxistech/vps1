CREATE INDEX idx_trades_raw_inst_time
    ON market_trades_raw (exchange_id, instrument_id, trade_time DESC);

-- Throttled top-N book snapshots. Full bid/ask levels are kept in JSONB
-- (array of [price, size]) so any depth-N feature can be recomputed later;
-- the flat columns are pre-derived standard microstructure signals:
--   mid        = (best_bid + best_ask) / 2
--   microprice = (best_bid * ask_size + best_ask * bid_size) / (bid_size + ask_size)
--   spread_bps = (best_ask - best_bid) / mid * 1e4
--   imbalance  = (bid_depth - ask_depth) / (bid_depth + ask_depth)
CREATE TABLE market_orderbook_snapshots (
    exchange_id     SMALLINT    NOT NULL,
    instrument_id   BIGINT      NOT NULL,
    snapshot_time   TIMESTAMPTZ NOT NULL,          -- exchange event time
    seq             BIGINT,                        -- exchange update sequence
    best_bid        NUMERIC     NOT NULL CHECK (best_bid >= 0),
    best_ask        NUMERIC     NOT NULL CHECK (best_ask >= 0),
    mid             NUMERIC     NOT NULL,
    microprice      NUMERIC,
    spread_bps      NUMERIC,
    bid_depth_n     NUMERIC     NOT NULL DEFAULT 0, -- sum of bid sizes, top N
    ask_depth_n     NUMERIC     NOT NULL DEFAULT 0, -- sum of ask sizes, top N
    imbalance_n     NUMERIC,
    levels          SMALLINT    NOT NULL DEFAULT 0, -- N captured per side
    bids            JSONB       NOT NULL DEFAULT '[]'::jsonb,  -- [[price,size],...]
    asks            JSONB       NOT NULL DEFAULT '[]'::jsonb,
    retention_class SMALLINT    NOT NULL DEFAULT 0,
    received_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (retention_class, exchange_id, instrument_id, snapshot_time),
    CONSTRAINT chk_book_cross CHECK (best_ask >= best_bid)
) PARTITION BY LIST (retention_class);

CREATE TABLE market_orderbook_snapshots_core PARTITION OF market_orderbook_snapshots
    FOR VALUES IN (1) PARTITION BY RANGE (snapshot_time);
CREATE TABLE market_orderbook_snapshots_other PARTITION OF market_orderbook_snapshots
    FOR VALUES IN (0) PARTITION BY RANGE (snapshot_time);

CREATE INDEX idx_book_inst_time
    ON market_orderbook_snapshots (exchange_id, instrument_id, snapshot_time DESC);

